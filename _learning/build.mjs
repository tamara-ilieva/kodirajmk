import { readFile, writeFile, mkdir, readdir, unlink } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { html, renderMarkdown } from './markdown.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
const read = file => readFile(path.join(root,file), 'utf8');
const json = async file => JSON.parse(await read(file));
const dirs = async file => (await readdir(path.join(root,file),{ withFileTypes:true })).filter(item => item.isDirectory()).map(item => item.name);
const manifestFile = '_learning/generated.json';
const stringList = values => Array.isArray(values) && values.every(value => typeof value === 'string');
const slug = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const outputPath = /^[a-z0-9-]+(?:\/[a-z0-9-]+)*\/index\.html$/;

function validate(record, directory, file) {
  if (!slug.test(directory) || record.slug !== directory || typeof record.title !== 'string' || !record.title.trim()) throw new Error('Invalid route metadata: ' + file);
}
function ordered(items) {
  return items.sort((a,b) => a.order - b.order || a.slug.localeCompare(b.slug));
}
const link = (base, route, label, extra = '') => '<a href="' + html(base + route) + '"' + extra + '>' + html(label) + '</a>';
const items = values => values.map(value => '<li>' + html(value) + '</li>').join('');
const availability = course => course.status === 'available' ? 'Достапен' : 'Наскоро';
const heading = (title,description) => '<header class="learning-heading"><h1>' + html(title) + '</h1><p>' + html(description) + '</p></header>';
const crumbs = (base, ...parents) => '<nav class="learning-crumbs" aria-label="Патека"><ol>' +
  [['','Почетна'],...parents].map(([route,title]) => '<li>' + (route === null ? '<span aria-current="page">' + html(title) + '</span>' : link(base,route,title)) + '</li>').join('') + '</ol></nav>';

function renderPage(template, route, title, description, body, kind) {
  const base = '../'.repeat(route.split('/').length - 1);
  const canonical = 'https://kodiraj.mk/' + route;
  const scripts = kind === 'catalog' && route === 'python/' ? '<script defer src="' + base + 'assets/js/courses.js?v=learning1"></script>' :
    '<script type="module" src="' + base + 'assets/js/learning.mjs"></script>';
  const metadata = '<title>' + html(title) + ' — kodiraj.mk</title>\n  <meta name="description" content="' + html(description) + '">\n' +
    '  <link rel="canonical" href="' + canonical + '">\n  <meta property="og:type" content="' + (kind === 'lesson' ? 'article' : 'website') + '">\n' +
    '  <meta property="og:title" content="' + html(title) + '">\n  <meta property="og:description" content="' + html(description) + '">\n' +
    '  <meta property="og:url" content="' + canonical + '">\n  <meta property="og:locale" content="mk_MK">\n  <meta property="og:image" content="https://kodiraj.mk/assets/images/social.png">';
  const file = route + 'index.html';
  const values = { base, metadata, scripts, body: body(base), skipTarget: kind === 'lesson' ? 'lesson-content' : 'learning-main' };
  return [file, '<!-- Generated by _learning/build.mjs -->\n' +
    template.replace(/\{\{(\w+)\}\}/g,(_,key) => values[key]).replace('data-page="python"', 'data-page="' + route.split('/')[0] + '"')];
}

function curriculum(base, course, current) {
  return '<ol class="learning-modules">' + course.modules.map(module => '<li id="' + html(module.slug) + '"><details' + (!current || module === current.moduleRecord ? ' open' : '') +
    '><summary>' + html(module.title) + '</summary>' +
    (module.lessons.length ? '<ul>' + module.lessons.map(lesson => '<li>' +
      link(base,lesson.route,lesson.title,' data-lesson="' + html(lesson.id) + '"' + (lesson === current ? ' aria-current="page"' : '')) +
      '<span data-completion-mark aria-hidden="true"></span></li>').join('') + '</ul>' : '<p class="fine-print">Наскоро</p>') +
    '</details></li>').join('') + '</ol>';
}

function progress(course) {
  return '<div class="learning-progress" data-progress="' + html(course.route) + '"><label>Напредок <progress max="100" value="0"></progress></label>' +
    '<span data-percent role="status">0%</span><div class="lesson-actions"><a data-continue hidden>Продолжи со учење</a>' +
    '<button type="button" data-reset hidden>Ресетирај</button></div><noscript>За локален напредок е потребен JavaScript.</noscript></div>';
}

function coursePage(page, subject, course) {
  page(course.route,course.title,course.description,base =>
    crumbs(base,[subject.route,subject.title],[null,course.title]) +
    '<div class="learning-overview">' + heading(course.title,course.description) +
    '<p class="learning-state">' + availability(course) + '</p>' +
    '<section><h2>Предуслови</h2><ul>' + items(course.prerequisites) + '</ul></section>' +
    '<section><h2>Цели на курсот</h2><ul>' + items(course.outcomes) + '</ul></section>' +
    '<section><h2>Наставна програма</h2>' + (course.lessons.length ? progress(course) : '') +
    (course.modules.length ? curriculum(base,course) : '<ol>' + items(course.outline) + '</ol>') + '</section></div>', 'course');
}

function lessonPage(page, visualizations, subject, course, lesson, index) {
  const rendered = renderMarkdown(lesson.markdown,visualizations);
  const module = lesson.moduleRecord;
  const previous = course.lessons[index - 1];
  const next = course.lessons[index + 1];
  const metadata = [
    lesson.minutes ? lesson.minutes + ' мин. читање' : '',
    lesson.difficulty,
    lesson.tags.join(', ')
  ].filter(Boolean).map(value => '<li>' + html(value) + '</li>').join('');
  const listSection = (label,values) => values.length ? '<h2>' + label + '</h2><ul>' + items(values) + '</ul>' : '';
  page(lesson.route,lesson.title,lesson.description,base =>
    crumbs(base,[subject.route,subject.title],[course.route,course.title],[course.route + '#' + module.slug,module.title],[null,lesson.title]) +
    '<div class="learning-grid"><aside class="learning-side"><details data-desktop-open open><summary>Наставна програма</summary><nav aria-label="Лекции">' +
    progress(course) + curriculum(base,course,lesson) + '</nav></details></aside>' +
    (rendered.toc.length ? '<aside class="learning-toc"><details data-desktop-open open><summary>Во оваа лекција</summary><nav aria-label="Содржина на лекцијата"><ul>' +
      rendered.toc.map(entry => '<li class="toc-level-' + entry.level + '">' + link('','#' + entry.id,entry.label) + '</li>').join('') +
      '</ul></nav></details></aside>' : '') +
    '<article id="lesson-content" tabindex="-1" class="learning-article" data-current-lesson="' + html(lesson.id) + '">' + heading(lesson.title,lesson.description) +
    (metadata ? '<ul class="lesson-meta">' + metadata + '</ul>' : '') +
    listSection('Цели на лекцијата',lesson.objectives) + listSection('Предуслови',lesson.prerequisites) + rendered.body +
    '<footer class="lesson-end"><label data-complete-control hidden><input type="checkbox" data-complete> Означи како завршена</label>' +
    '<nav aria-label="Редослед на лекции">' +
    (previous ? link(base,previous.route,'Претходно · ' + previous.title,' rel="prev"') : '') +
    (next ? link(base,next.route,'Следно · ' + next.title,' rel="next"') : link(base,course.route,'Назад кон курсот')) +
    '</nav></footer></article></div>', 'lesson');
}

async function collectPages() {
  const output = new Map();
  const ids = new Set();
  const template = await read('_learning/layout.html');
  const visualizations = new Map(Object.entries(await json('_learning/visualizations.json')));
  for (const [name, module] of visualizations) {
    if (!slug.test(name) || !/^[a-z0-9-]+\.mjs$/.test(module)) throw new Error('Invalid visualization registration: ' + name);
    await read('assets/js/visualizations/' + module);
  }

  function page(...args) {
    const [file, content] = renderPage(template, ...args);
    if (output.has(file)) throw new Error('Duplicate page: ' + file);
    output.set(file, content);
  }

  for (const subjectSlug of await dirs('_learning/content')) {
    const source = '_learning/content/' + subjectSlug;
    const subject = await json(source + '/subject.json');
    validate(subject,subjectSlug,source);
    subject.route = subject.slug + '/';
    const courses = [];
    for (const courseSlug of await dirs(source)) {
      const courseDir = source + '/' + courseSlug;
      const course = await json(courseDir + '/course.json');
      validate(course,courseSlug,courseDir);
      if (!['available','coming-soon'].includes(course.status) || !Number.isInteger(course.order) ||
          typeof course.description !== 'string' || !['prerequisites','outcomes','outline'].every(field => stringList(course[field]))) throw new Error('Invalid course metadata: ' + courseDir);
      course.route = subject.route + course.slug + '/';
      course.modules = [];
      for (const moduleSlug of await dirs(courseDir)) {
        const moduleDir = courseDir + '/' + moduleSlug;
        const module = await json(moduleDir + '/module.json');
        validate(module,moduleSlug,moduleDir);
        if (!Number.isInteger(module.order)) throw new Error('Invalid module order: ' + moduleDir);
        module.lessons = [];
        const lessonSlugs = new Set();
        for (const name of await readdir(path.join(root,moduleDir))) {
          if (!name.endsWith('.md')) continue;
          const file = moduleDir + '/' + name;
          const match = /^---\r?\n([\s\S]+?)\r?\n---(?:\r?\n|$)([\s\S]*)$/.exec((await read(file)).replace(/^\uFEFF/,''));
          if (!match) throw new Error('Missing JSON front matter: ' + file);
          const lesson = JSON.parse(match[1]);
          validate(lesson,name.slice(0,-3),file);
          if (typeof lesson.id !== 'string' || !slug.test(lesson.id) || ids.has(lesson.id) || lessonSlugs.has(lesson.slug) ||
              lesson.course !== course.slug || lesson.module !== module.slug || !['draft','published'].includes(lesson.status) ||
              !Number.isInteger(lesson.order) || !Number.isInteger(lesson.minutes) || lesson.minutes < 0 ||
              !['objectives','prerequisites','tags'].every(field => stringList(lesson[field]))) {
            throw new Error('Invalid lesson metadata: ' + file);
          }
          ids.add(lesson.id);
          lessonSlugs.add(lesson.slug);
          if (lesson.status !== 'published' || course.status !== 'available') continue;
          if (!match[2].trim() || !lesson.description?.trim()) throw new Error('Published lesson requires a description and body: ' + file);
          Object.assign(lesson,{ route: course.route + module.slug + '/' + lesson.slug + '/', moduleRecord:module, markdown:match[2] });
          module.lessons.push(lesson);
        }
        ordered(module.lessons);
        course.modules.push(module);
      }
      ordered(course.modules);
      course.lessons = course.modules.flatMap(module => module.lessons);
      courses.push(course);
      coursePage(page,subject,course);
      course.lessons.forEach((lesson,index) => lessonPage(page,visualizations,subject,course,lesson,index));
    }
    ordered(courses);
    page(subject.route,subject.title,subject.description,base => crumbs(base,[null,subject.title]) +
      '<div class="learning-overview learning-catalog-page">' + heading(subject.title,subject.description) + '<section><h2>Курсеви</h2><ul class="learning-catalog">' +
      courses.map(course => {
        const available = course.status === 'available';
        const count = course.modules.length || course.outline.length;
        const unit = course.modules.length
          ? (count === 1 ? 'модул' : 'модули')
          : (count === 1 ? 'планирана тема' : 'планирани теми');
        return '<li' + (available ? ' class="course-card-available"' : '') + '><h3>' + html(course.title) +
          '</h3><p>' + html(course.description) + '</p>' +
          (count ? '<p class="course-card-count">' + count + ' ' + unit + '</p>' : '') +
          (available
            ? link(base,course.route,'Отвори курс',' class="course-card-action" aria-label="Отвори курс: ' + html(course.title) + '"')
            : '<span class="learning-state">' + availability(course) + '</span>') + '</li>';
      }).join('') + '</ul></section>' +
      (subject.slug === 'python' ? '<section id="course-preview" aria-label="Преглед на код"></section>' : '') + '</div>', 'catalog');
  }
  return output;
}

export async function writePages({ check = false } = {}) {
  const output = await collectPages();
  let previousFiles = [];
  try { previousFiles = await json(manifestFile); }
  catch (error) { if (error.code !== 'ENOENT') throw error; }
  const staleFiles = previousFiles.filter(file => !output.has(file));
  for (const file of staleFiles) {
    if (!outputPath.test(file)) throw new Error('Invalid generated path: ' + file);
    let existing;
    try { existing = await read(file); }
    catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (existing && !existing.startsWith('<!-- Generated by _learning/build.mjs -->')) throw new Error('Refusing to remove a hand-edited page: ' + file);
    if (existing && check) throw new Error('Stale published route: ' + file);
    if (existing && !check) await unlink(path.join(root,file));
  }
  const files = new Map(output);
  files.set(manifestFile,JSON.stringify([...output.keys()].sort(),null,2) + '\n');
  for (const [file,body] of files) {
    if (check) {
      if ((await read(file)).replace(/\r\n/g,'\n') !== body.replace(/\r\n/g,'\n')) throw new Error('Stale generated file: ' + file);
    } else {
      await mkdir(path.join(root,path.dirname(file)),{ recursive:true });
      await writeFile(path.join(root,file),body.replace(/\r\n/g,'\n'));
    }
  }
  console.log((check ? 'Verified ' : 'Generated ') + output.size + ' learning pages.');
}

if (globalThis.process) await writePages({ check: process.argv.includes('--check') });
